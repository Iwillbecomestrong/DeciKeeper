def report(title, sections, target_min):
    total = 0
    rows = []
    for name, text in sections.items():
        n = count(text)
        total += n
        rows.append((name, n))

    print("=" * 68)
    print(title)
    print("=" * 68)
    print(f"{'节点':<34}{'字数':>6}{'本节时长':>10}{'累计时间码':>12}")
    print("-" * 68)
    elapsed = 0.0
    for name, n in rows:
        mins = n / RATE
        print(f"{name:<34}{n:>6}{mins:>9.1f}分{fmt_ts(elapsed):>12}")
        elapsed += mins
    print("-" * 68)
    print(f"{'合计':<34}{total:>6}{total / RATE:>9.1f}分")
    print()
    print(f"目标时长 {target_min:g} 分钟 → 可容纳 {int(target_min * RATE)} 字"
          f"（{int(target_min * 220)}~{int(target_min * 250)} 字 @220/250）")
    delta = total - target_min * RATE
    verdict = "超出" if delta > 0 else "结余"
    print(f"当前{verdict} {abs(delta):.0f} 字（{abs(delta) / RATE * 60:.0f} 秒）")
    print(f"实际全长约 {elapsed:.2f} 分钟（@230 字/分）")
    print()
    return total


def fmt_ts(mins):
    s = int(mins * 60)
    return f"{s // 60}:{s % 60:02d}"


def export_video1(path):
    """把视频 1 稿件导出为可直接照着念的 Markdown 定稿。

    导出而非手写，是为了保证 narration_count.py 始终是唯一真相源：
    改稿只需改字典再跑一次 --export，不会出现两份内容对不上的情况。
    """
    lines = []
    total = sum(count(t) for t in VIDEO1.values())
    elapsed = 0.0
    lines.append("# 视频 1 定稿旁白")
    lines.append("")
    lines.append("> 《我做了一个自己每天都在用的软件，现在把它开源了》")
    lines.append(f"> 全长约 {total / RATE:.1f} 分钟（{total} 字，@230 字/分钟）")
    lines.append(">")
    lines.append("> ⚠️ 本文件由 `narration_count.py --export` 自动生成，**请勿手改**。")
    lines.append("> 改稿请改 `narration_count.py` 里的 `VIDEO1` 字典后重新导出。")
    lines.append("")

    for name, text in VIDEO1.items():
        n = count(text)
        start = fmt_ts(elapsed)
        elapsed += n / RATE
        end = fmt_ts(elapsed)
        lines.append(f"## {name}")
        lines.append("")
        lines.append(f"`{start} – {end}`　·　{n} 字")
        lines.append("")
        lines.append(text)
        lines.append("")

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"已导出：{path}（{total} 字 / {total / RATE:.1f} 分钟）")


